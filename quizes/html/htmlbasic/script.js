let currentFileHandlingQuestion = 0;
let fileHandlingScore = 0;
let fileHandlingAttempt = JSON.parse(localStorage.getItem('htmlbasic')) || 0;
let fileHandlingScores = JSON.parse(localStorage.getItem('htmlbasics')) || [];

const fileHandlingQuestionElement = document.getElementById('question');
const fileHandlingChoicesElement = document.getElementById('choices');
const fileHandlingResultElement = document.getElementById('result');
const fileHandlingNextButton = document.getElementById('next-btn');
const fileHandlingProgressElement = document.getElementById('current-question');
const fileHandlingScoresList = document.getElementById('scores-list');
const fileHandlingReattemptButton = document.getElementById('reattempt-btn');

function loadFileHandlingQuestion() {
    const q = fileHandlingQuizData[currentFileHandlingQuestion];
    fileHandlingQuestionElement.textContent = q.question;

    // Clear result text
    fileHandlingResultElement.textContent = '';

    // Reset choices
    fileHandlingChoicesElement.innerHTML = '';
    q.choices.forEach((choice, index) => {
        const li = document.createElement('li');
        li.textContent = choice;
        li.addEventListener('click', () => checkFileHandlingAnswer(index));
        li.dataset.index = index; // Add data attribute for index
        fileHandlingChoicesElement.appendChild(li);
    });

    // Update progress
    fileHandlingProgressElement.textContent = currentFileHandlingQuestion + 1;

    // Enable next button only after a choice is selected
    fileHandlingNextButton.disabled = true;
}

function checkFileHandlingAnswer(index) {
    const correctAnswerIndex = fileHandlingQuizData[currentFileHandlingQuestion].correctAnswer;
    const choices = fileHandlingChoicesElement.querySelectorAll('li');
    const selectedChoice = choices[index];

    // Add selected class to the clicked choice
    selectedChoice.classList.add('selected');

    if (index === correctAnswerIndex) {
        fileHandlingScore++;
        fileHandlingResultElement.textContent = 'Correct!';
        selectedChoice.classList.add('correct');
    } else {
        fileHandlingResultElement.textContent = `Wrong! The correct answer is: ${fileHandlingQuizData[currentFileHandlingQuestion].choices[correctAnswerIndex]}`;
        selectedChoice.classList.add('incorrect');

        // Highlight the correct answer
        choices[correctAnswerIndex].classList.add('correct');
    }
    disableFileHandlingChoices();
    fileHandlingNextButton.disabled = false;
}

function disableFileHandlingChoices() {
    fileHandlingChoicesElement.querySelectorAll('li').forEach(choice => {
        choice.style.cursor = 'not-allowed';
        // Don't change background color here, we're using classes now
    });
}

function nextFileHandlingQuestion() {
    currentFileHandlingQuestion++;
    if (currentFileHandlingQuestion < fileHandlingQuizData.length) {
        loadFileHandlingQuestion();
        fileHandlingResultElement.textContent = '';
        fileHandlingNextButton.disabled = true;
    } else {
        showFileHandlingResults();
    }
}

function showFileHandlingResults() {
    // Create a result container with modern styling
    const resultContainer = document.createElement('div');
    resultContainer.style.padding = '2rem';
    resultContainer.style.backgroundColor = 'var(--dark-surface-2)';
    resultContainer.style.borderRadius = 'var(--border-radius-lg)';
    resultContainer.style.marginBottom = '2rem';
    resultContainer.style.border = '1px solid var(--dark-border)';
    resultContainer.style.animation = 'fadeIn 0.5s ease-out';

    // Add result heading
    const resultHeading = document.createElement('h2');
    resultHeading.textContent = 'Quiz Completed!';
    resultHeading.style.marginBottom = '1rem';
    resultHeading.style.color = 'var(--primary-400)';
    resultContainer.appendChild(resultHeading);

    // Add score information
    const scoreInfo = document.createElement('p');
    scoreInfo.innerHTML = `You scored <strong>${fileHandlingScore}</strong> out of <strong>${fileHandlingQuizData.length}</strong>`;
    scoreInfo.style.fontSize = '1.2rem';
    scoreInfo.style.marginBottom = '1.5rem';
    resultContainer.appendChild(scoreInfo);

    // Add performance message
    const performanceMsg = document.createElement('p');
    const percentage = (fileHandlingScore / fileHandlingQuizData.length) * 100;
    if (percentage >= 80) {
        performanceMsg.textContent = 'Excellent! You have a great understanding of HTML basics.';
        performanceMsg.style.color = 'var(--success-color)';
    } else if (percentage >= 60) {
        performanceMsg.textContent = 'Good job! You have a solid understanding of HTML basics.';
        performanceMsg.style.color = 'var(--primary-color)';
    } else {
        performanceMsg.textContent = 'Keep practicing! Review the HTML basics concepts.';
        performanceMsg.style.color = 'var(--warning-color)';
    }
    resultContainer.appendChild(performanceMsg);

    // Clear and update the UI
    fileHandlingQuestionElement.textContent = '';
    fileHandlingChoicesElement.innerHTML = '';
    fileHandlingChoicesElement.appendChild(resultContainer);
    fileHandlingResultElement.textContent = '';
    fileHandlingNextButton.style.display = 'none';
    fileHandlingReattemptButton.style.display = 'inline-block';

    // Increment attempt count
    fileHandlingAttempt++;
    localStorage.setItem('htmlbasic', JSON.stringify(fileHandlingAttempt));

    // Save score to scores array
    fileHandlingScores.push({
        attempt: fileHandlingAttempt,
        score: fileHandlingScore
    });
    localStorage.setItem('htmlbasics', JSON.stringify(fileHandlingScores));

    // Display scores
    displayFileHandlingScores();
}

function displayFileHandlingScores() {
    fileHandlingScoresList.innerHTML = '';

    if (fileHandlingScores.length === 0) {
        const emptyMessage = document.createElement('li');
        emptyMessage.textContent = 'No previous attempts';
        emptyMessage.style.fontStyle = 'italic';
        emptyMessage.style.color = 'var(--text-secondary)';
        fileHandlingScoresList.appendChild(emptyMessage);
        return;
    }

    fileHandlingScores.forEach((scoreItem, index) => {
        const li = document.createElement('li');
        const percentage = (scoreItem.score / fileHandlingQuizData.length) * 100;

        // Create a more detailed score item
        const attemptLabel = document.createElement('span');
        attemptLabel.textContent = `Attempt ${scoreItem.attempt}: `;
        attemptLabel.style.fontWeight = '500';
        li.appendChild(attemptLabel);

        const scoreValue = document.createElement('span');
        scoreValue.textContent = `${scoreItem.score} / ${fileHandlingQuizData.length} `;
        scoreValue.style.fontWeight = '600';
        li.appendChild(scoreValue);

        const percentageSpan = document.createElement('span');
        percentageSpan.textContent = `(${percentage.toFixed(0)}%)`;

        // Color code the percentage based on performance
        if (percentage >= 80) {
            percentageSpan.style.color = 'var(--success-color)';
        } else if (percentage >= 60) {
            percentageSpan.style.color = 'var(--primary-color)';
        } else {
            percentageSpan.style.color = 'var(--warning-color)';
        }

        li.appendChild(percentageSpan);

        // Add animation delay for staggered appearance
        li.style.animationDelay = `${index * 0.1}s`;

        fileHandlingScoresList.appendChild(li);
    });
}

function reattemptFileHandlingQuiz() {
    // Reset quiz state
    currentFileHandlingQuestion = 0;
    fileHandlingScore = 0;

    // Show next button and hide reattempt button
    fileHandlingNextButton.style.display = 'inline-block';
    fileHandlingReattemptButton.style.display = 'none';

    // Clear result text
    fileHandlingResultElement.textContent = '';

    // Add a smooth transition effect
    const container = document.querySelector('.container');
    container.style.opacity = '0.5';
    container.style.transform = 'scale(0.98)';

    // After a short delay, reset the container and load the first question
    setTimeout(() => {
        container.style.opacity = '1';
        container.style.transform = 'scale(1)';
        loadFileHandlingQuestion();
    }, 300);
}

fileHandlingNextButton.addEventListener('click', nextFileHandlingQuestion);
fileHandlingReattemptButton.addEventListener('click', reattemptFileHandlingQuiz);

// Initial load
loadFileHandlingQuestion();
displayFileHandlingScores();
